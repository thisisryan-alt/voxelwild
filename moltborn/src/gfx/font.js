const GW = 5, GH = 8, ADV = 6, LH = 10;
export const FONT = { GW, GH, ADV, LH };
const glyphs = {};
for (const [k, v] of Object.entries(G)) glyphs[k] = v.split(' ').map((r) => r.split('').map((c) => c === '1'));

const atlasCache = new Map();
function atlas(color) {
  let a = atlasCache.get(color);
  if (a) return a;
  const keys = Object.keys(glyphs);
  const cv = document.createElement('canvas'); cv.width = keys.length * 6; cv.height = 8;
  const g = cv.getContext('2d'); g.fillStyle = color;
  const map = {};
  keys.forEach((k, i) => {
    map[k] = i * 6;
    glyphs[k].forEach((row, y) => row.forEach((on, x) => { if (on) g.fillRect(i * 6 + x, y, 1, 1); }));
  });
  a = { cv, map }; atlasCache.set(color, a); return a;
}

export function textWidth(str, scale = 1) {
  let w = 0, best = 0;
  for (const ch of String(str)) { if (ch === '\n') { best = Math.max(best, w); w = 0; } else w += ADV; }
  return Math.max(0, Math.max(best, w) - 1) * scale;
}

// Word-wrap into lines no wider than maxW pixels
export function wrapText(str, maxW, scale = 1) {
  const out = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const test = line ? line + ' ' + word : word;
      if (textWidth(test, scale) > maxW && line) { out.push(line); line = word; } else line = test;
    }
    out.push(line);
  }
  return out;
}

// opts: color, scale, shadow (color), outline (color), align ('left'|'center'|'right'), alpha
export function drawText(ctx, str, x, y, opts = {}) {
  const { color = '#ffffff', scale = 1, shadow = null, outline = null, align = 'left', alpha = 1 } = opts;
  str = String(str);
  x = Math.round(x); y = Math.round(y);
  const lines = str.split('\n');
  const prevA = ctx.globalAlpha; ctx.globalAlpha = prevA * alpha;
  lines.forEach((line, li) => {
    const w = textWidth(line, scale);
    const cx = align === 'center' ? x - Math.round(w / 2) : align === 'right' ? x - w : x;
    const cy = y + li * LH * scale;
    const pass = (col, ox, oy) => {
      const at = atlas(col);
      let px = cx + ox;
      for (const ch of line) {
        const gx = at.map[ch] ?? at.map['?'];
        if (ch !== ' ') ctx.drawImage(at.cv, gx, 0, 5, 8, px, cy + oy, 5 * scale, 8 * scale);
        px += ADV * scale;
      }
    };
    if (outline) { for (const [ox, oy] of [[-1, 0], [1, 0], [0, -1], [0, 1]]) pass(outline, ox * scale, oy * scale); }
    if (shadow) pass(shadow, scale, scale);
    pass(color, 0, 0);
  });
  ctx.globalAlpha = prevA;
}
